// ==================== חישוב תאריכים/זמנים אמיתיים ====================

async function computeUpcoming(daysAhead = 400) {
  const hebcal = await loadHebcal();
  const { HebrewCalendar } = hebcal;
  const location = resolveLocation(hebcal);
  const now = new Date();
  const end = new Date(now.getTime() + daysAhead * 86400000);

  const events = HebrewCalendar.calendar({ start: now, end, location, il: true, candlelighting: true, sedrot: false });
  const candles = events.filter((e) => e.getDesc() === "Candle lighting" && e.eventTime);
  const havdalahs = events.filter((e) => e.getDesc() === "Havdalah" && e.eventTime);

  function timesFor(hDate) {
    // מחפשים הדלקה סמוכה לפני היום (ערב החג) והבדלה סמוכה בסיום
    const d0 = new Date(hDate.getFullYear(), hDate.getMonth(), hDate.getDate());
    const candle = candles.find((c) => {
      const cd = new Date(c.eventTime);
      return Math.abs(cd - d0) < 2 * 86400000 && cd < d0.getTime() + 86400000;
    });
    const havdalah = havdalahs.find((h) => h.eventTime > (candle ? candle.eventTime : d0));
    return {
      candleLighting: candle ? { date: dateStr(candle.eventTime), time: timeStr(candle.eventTime) } : null,
      havdalah: havdalah ? { date: dateStr(havdalah.eventTime), time: timeStr(havdalah.eventTime) } : null
    };
  }

  const results = [];
  for (const entry of REGISTRY) {
    if (entry.id === "shabbat") continue; // מחושב בנפרד — כל שבוע
    const allMatches = entry.hebcalMatch ? events.filter((e) => entry.hebcalMatch.test(e.getDesc())) : [];
    if (!allMatches.length) continue;
    // חלון של 400 יום תופס גם את ההופעה הבאה בשנה שאחרי — לוקחים רק את האשכול הרצוף
    // הראשון (פער של יותר מ-3 ימים בין שני אירועים = מעבר לשנה הבאה, לא אותו חג)
    allMatches.sort((a, b) => a.getDate().greg() - b.getDate().greg());
    const cluster = [allMatches[0]];
    for (let i = 1; i < allMatches.length; i++) {
      const gapDays = (allMatches[i].getDate().greg() - cluster[cluster.length - 1].getDate().greg()) / 86400000;
      if (gapDays > 3) break;
      cluster.push(allMatches[i]);
    }
    const first = cluster[0];
    const last = cluster[cluster.length - 1];
    const startDate = first.getDate().greg();
    const endDate = last.getDate().greg();
    results.push({
      id: entry.id, name: entry.name, icon: entry.icon, tagline: entry.tagline,
      startDate: dateStr(startDate), endDate: dateStr(endDate),
      daysAway: Math.round((startDate - now) / 86400000),
      ...timesFor(startDate)
    });
  }
  results.sort((a, b) => a.daysAway - b.daysAway);
  return results;
}

function getContent(id) {
  const entry = REGISTRY.find((e) => e.id === id);
  if (!entry) return null;
  const { hebcalMatch, ...rest } = entry;
  return rest;
}

function listAll() {
  return REGISTRY.map((e) => ({ id: e.id, name: e.name, icon: e.icon, tagline: e.tagline, intro: e.intro }));
}

// ==================== סנכרון אוטומטי ליומן העסקי ====================
// מוסיף אירוע לכל חג קרוב שעוד אין לו אירוע ביומן (לפי כותרת+תאריך זהים) — לא יוצר כפילויות
// גם אם רץ שוב ושוב (בעליה של השרת, או בבקשה ידנית).
async function syncToCalendar(baseDir) {
  const bizFactory = require("./business");
  const biz = bizFactory(baseDir);
  const upcoming = await computeUpcoming(400);
  const existing = biz.listCalendar();
  let added = 0;
  for (const h of upcoming) {
    const title = `${h.icon} ${h.name}`;
    const already = existing.some((e) => e.date === h.startDate && e.title === title);
    if (already) continue;
    const timeNote = h.candleLighting ? `כניסה ${h.candleLighting.time}${h.havdalah ? " · יציאה " + h.havdalah.time : ""}` : "";
    biz.saveCalendarEntry({
      date: h.startDate, time: h.candleLighting ? h.candleLighting.time : "",
      title, type: "holiday",
      notes: [h.tagline, timeNote].filter(Boolean).join(" — ")
    });
    added++;
  }
  return { ok: true, added, total: upcoming.length };
}

module.exports = { REGISTRY, computeUpcoming, getContent, listAll, syncToCalendar };
