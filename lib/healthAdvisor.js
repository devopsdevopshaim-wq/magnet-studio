const FIELD_LABELS = {
  age: "גיל", sex: "מין", height: 'גובה ס"מ', weight: 'משקל ק"ג', waist: 'היקף מותן ס"מ',
  goalWeight: "משקל יעד", concernText: "תיאור הבעיה", duration: "משך", pattern: "דפוס",
  meds: "תרופות", history: "רקע רפואי", meals: "ארוחות ביום", window: "חלון אכילה",
  upf: "מזון אולטרה-מעובד", drinks: "משקאות ממותקים/אלכוהול", sleep: "שעות שינה", stress: "מתח",
  aerobic: "דקות אירובי/שבוע", strength: "ימי כוח/שבוע", steps: "צעדים/יום",
  limits: "מגבלות תנועה", goals: "מטרות"
};

function buildPrompt(d) {
  d = d || {};
  const L = [];
  L.push("אתה עוזר בריאות שמנסח תוכנית מבוססת-הנחיות בעברית. אינך רופא, אינך מאבחן ואינך רושם תרופות. אל תמציא נתונים על המשתמש שלא נמסרו.");
  L.push("");
  L.push("להלן נתוני המשתמש ולאחריהם תמצית ההנחיות. כתוב תוכנית אישית קונקרטית ומספרית, בעברית, במבנה הבא עם כותרות מודגשות (**):");
  L.push("1. תמונת מצב — BMI, סיווג, היקף מותן, והגורמים הבולטים שעולים מהנתונים.");
  L.push("2. דגלים אדומים — אם המשתמש סימן, ציין זאת ראשון והמלץ לפנות לרופא/ה לפני תוכנית עצמאית; פרט אילו.");
  L.push("3. תזונה — יעד קלורי משוער לגירעון ~500, חלוקת מאקרו, מה להפחית קודם, ודוגמת יום אחת מלאה.");
  L.push("4. פעילות גופנית — תוכנית ל-4 שבועות ראשונים: דקות אירובי/שבוע, ימי כוח ותרגילים, יעד צעדים; התאמה למגבלות.");
  L.push("5. נפיחות ועיכול — צעדים לפי הסימפטומים שסומנו בלבד; אם רלוונטי, שלבי ה-FODMAP.");
  L.push("6. גורמים נוספים — שינה, מתח, אלכוהול, בדיקת תרופות; מתי לשקול בדיקות דם, הפניה למומחה, או תרופות מרשם.");
  L.push("7. מעקב — 4-8 שבועות: מה למדוד ואילו יעדים.");
  L.push("8. סייג קצר: זו אינה המלצה רפואית.");
  L.push("אורך: עד ~650 מילים. אם חסרים נתונים חשובים, ציין זאת בקצרה במקום המתאים.");
  L.push("");
  L.push("=== נתוני המשתמש ===");
  for (const [k, label] of Object.entries(FIELD_LABELS)) {
    if (d[k] != null && String(d[k]).trim()) L.push(`${label}: ${String(d[k]).trim()}`);
  }
  if (Array.isArray(d.concern) && d.concern.length) L.push("תסמינים שסומנו: " + d.concern.join(", "));
  if (Array.isArray(d.condition) && d.condition.length) L.push("רקע/אבחנות: " + d.condition.join(", "));
  if (Array.isArray(d.flags) && d.flags.length) L.push("דגלים אדומים שסומנו: " + d.flags.join("; "));
  const h = parseFloat(d.height), w = parseFloat(d.weight);
  if (h > 100 && w > 20) {
    const bmi = w / Math.pow(h / 100, 2);
    if (isFinite(bmi)) L.push("BMI מחושב: " + bmi.toFixed(1));
  }
  L.push("");
  L.push("=== תמצית ההנחיות ===");
  L.push(KB_SUMMARY);
  return L.join("\n");
}

async function analyze(data) {
  const prompt = buildPrompt(data);
  const r = await askAI(prompt, { timeout: 120000, sessionTag: "health-compass" });
  if (!r) return { ok: false, error: "אין מנוע AI זמין כרגע — הפעל את JARVIS ב-n8n, את Ollama המקומי, או הגדר מפתח ספק ענן." };
  return { ok: true, text: r.text, source: r.source };
}

module.exports = { analyze, buildPrompt, KB_SUMMARY };
